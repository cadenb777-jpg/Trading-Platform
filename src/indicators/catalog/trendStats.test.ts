const SPY: ExternalPoint[] = fixtureBars(300, 7).map((b) => ({ time: b.time, values: { close: b.close } }));
const run = (def: IndicatorDef, bars: Bar[], ext: ExternalPoint[] | undefined = SPY) => def.compute(bars, defaultParams(def), ext);
const close = (got: number, want: number) => Math.abs(got - want) <= 1e-6 * Math.max(1, Math.abs(want));

describe('trend/volatility/statistics catalog: reference values', () => {
  it('has a reference for every indicator', () => {
    expect(ALL.map((d) => d.id).filter((id) => !REF[id])).toEqual([]);
  });

  for (const def of ALL) {
    it(`${def.id} matches the reference`, () => {
      const out = run(def, FIXTURE);
      for (const [plot, ref] of Object.entries(REF[def.id] ?? {})) {
        const values = out[plot];
        expect(values, `${def.id}.${plot}`).toHaveLength(FIXTURE.length);
        if (ref.first !== undefined) expect(values.findIndex(Number.isFinite), `${def.id}.${plot} warm-up`).toBe(ref.first);
        for (const [i, want] of Object.entries(ref.at)) {
          const got = values[Number(i)];
          if (want === null) expect(Number.isNaN(got), `${def.id}.${plot}[${i}] blank`).toBe(true);
          else expect(close(got, want), `${def.id}.${plot}[${i}] = ${got}, want ${want}`).toBe(true);
        }
      }
    });
  }
});

describe('trend/volatility/statistics catalog: definitions', () => {
  it('ids are unique and reach the library unchanged', () => {
    const ids = TREND_STATS.map((d) => d.id);
    expect(new Set(ids).size).toBe(ids.length);
    for (const def of TREND_STATS) {
      expect(INDICATORS.filter((d) => d.id === def.id), def.id).toHaveLength(1);
      expect(getIndicator(def.id), `${def.id} is shadowed by an existing indicator`).toBe(def);
    }
    expect(TREND_STATS.length).toBeGreaterThanOrEqual(90);
    for (const def of BENCH) expect(getIndicator(def.id), def.id).toBeUndefined();
  });

  it('every indicator has a description, a guide, valid inputs and plots', () => {
    for (const def of ALL) {
      expect(['Trend', 'Volatility', 'Statistics']).toContain(def.category);
      expect(def.description.length, def.id).toBeGreaterThan(20);
      const g = GUIDES[def.id];
      expect(g?.what.length, def.id).toBeGreaterThan(10);
      expect(g.use.length && g.signals.length, def.id).toBeGreaterThan(0);
      expect(new Set(def.inputs.map((i) => i.key)).size).toBe(def.inputs.length);
      for (const inp of def.inputs) {
        if (inp.type !== 'number') continue;
        expect(inp.default >= (inp.min ?? -Infinity) && inp.default <= (inp.max ?? Infinity), `${def.id}.${inp.key}`).toBe(true);
      }
      expect(def.plots.length).toBeGreaterThan(0);
      expect(new Set(def.plots.map((p) => p.key)).size).toBe(def.plots.length);
      for (const p of def.plots) expect(p.color, `${def.id}.${p.key}`).toMatch(/^#[0-9a-f]{6}$/);
    }
  });

  const flat: Bar[] = FIXTURE.map((b) => ({ ...b, open: 100, high: 100, low: 100, close: 100, volume: 1e6 }));
  const flatSpy = flat.map((b) => ({ time: b.time, values: { close: 100 } }));
  const cases: [string, Bar[], ExternalPoint[]][] = [
    ['5 bars', FIXTURE.slice(0, 5), SPY],
    ['flat prices', flat, flatSpy],
    ['no bars', [], SPY],
  ];
  for (const [name, bars, ext] of cases) {
    it(`survives ${name} (no infinities, arrays aligned)`, () => {
      for (const def of ALL) {
        const out = run(def, bars, ext);
        for (const p of def.plots) {
          expect(out[p.key], `${def.id}.${p.key}`).toHaveLength(bars.length);
          expect(out[p.key].every((v) => Number.isNaN(v) || Number.isFinite(v)), `${def.id}.${p.key}`).toBe(true);
        }
      }
    });
  }

  it('flat prices read as no volatility and no trend', () => {
    const at = (id: string, plot: string) => run(getIndicator(id)!, flat, flatSpy)[plot][299];
    for (const [id, plot] of [['hv', 'hv'], ['natr', 'natr'], ['parkinson', 'vol'], ['yangzhang', 'vol'], ['ulcer', 'ui'], ['variance', 'var'], ['maxdd', 'dd'], ['lrslope', 'slope']]) expect(at(id, plot), id).toBe(0);
    expect(at('trendscore', 'score')).toBe(0);
    expect(at('streak', 'streak')).toBe(0);
  });
});

describe('SPY comparisons', () => {
  const self = FIXTURE.map((b) => ({ time: b.time, values: { close: b.close } }));
  it('a stock against itself has beta 1, correlation 1 and ratio 1', () => {
    expect(run(bench('betaspy'), FIXTURE, self).beta[299]).toBeCloseTo(1, 12);
    expect(run(bench('corrspy'), FIXTURE, self).corr[299]).toBeCloseTo(1, 12);
    expect(run(bench('relspy'), FIXTURE, self).ratio[299]).toBe(1);
  });

  it('stays blank without SPY data and on intraday bars (no look-ahead)', () => {
    expect(run(bench('relspy'), FIXTURE, []).ratio.every(Number.isNaN)).toBe(true);
    const hourly = FIXTURE.map((b, i) => ({ ...b, time: 1700000000 + i * 3600 }));
    const hourlySpy = hourly.map((b) => ({ time: b.time, values: { close: b.close } }));
    expect(run(bench('betaspy'), hourly, hourlySpy).beta.every(Number.isNaN)).toBe(true);
  });
});
