/** Plain-English guides for the overlay family (moving averages, bands, trend stops, levels). */
import type { IndicatorGuide } from '../info';

const maGuide = (what: string, extra?: string, tip?: string): IndicatorGuide => ({
  what,
  use: ['Price above a rising line = uptrend; below a falling line = downtrend.', extra ?? 'Compare it with a plain EMA of the same length to see how it differs.'],
  signals: ['Price crossing the line, or the line turning up or down.', 'A fast version crossing a slow one marks a trend change.'],
  ...(tip ? { tip } : {}),
});

const bandGuide = (what: string, use: string, tip?: string): IndicatorGuide => ({
  what,
  use: [use, 'The middle line shows the trend; the outer lines show how far a normal move reaches.'],
  signals: ['In a range, touches of the outer lines tend to snap back to the middle.', 'A close outside the band in a new trend can start a breakout; don’t fade it blindly.'],
  ...(tip ? { tip } : {}),
});

const stopGuide = (what: string, tip?: string): IndicatorGuide => ({
  what,
  use: ['Use the line under price as a trailing stop for long trades and the line above price for shorts.', 'Green = the up-trend is intact; red = the down-trend is intact.'],
  signals: ['A close through the line flips the trend: exit, or consider the other side.', 'Wait for the close, not an intrabar poke, to cut false flips.'],
  ...(tip ? { tip } : {}),
});

const pivotGuide = (what: string, tip?: string): IndicatorGuide => ({
  what,
  use: ['Levels are fixed for the whole day (or week/month); set the period in settings.', 'R levels above price are resistance, S levels below are support; P is the balance point.'],
  signals: ['Opening above P = a bullish tilt; below = bearish.', 'Bounces at S1/R1 in quiet markets; breaks through R2/S2 often mean a trend day.'],
  tip: tip ?? 'On intraday charts the day is the New York date; on daily or longer charts it uses each bar’s own date.',
});

